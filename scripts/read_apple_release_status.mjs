import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import jwt from '../functions/node_modules/jsonwebtoken/index.js';
const keyId='RUVLFC92KQ';
const release=JSON.parse(fs.readFileSync('functions/ios_release.json','utf8'));
const build=String(release.candidateBuildNumber);
const key=fs.readFileSync(path.join(os.homedir(),'.appstoreconnect','private_keys',`AuthKey_${keyId}.p8`));
const token=jwt.sign({iss:'0e798661-3c05-4b2a-9788-386ecf469c42',aud:'appstoreconnect-v1'},key,{algorithm:'ES256',keyid:keyId,expiresIn:300});
const query=new URLSearchParams({'filter[app]':'6792811282','filter[version]':build,include:'preReleaseVersion',limit:'5'});
const response=await fetch(`https://api.appstoreconnect.apple.com/v1/builds?${query}`,{headers:{Authorization:`Bearer ${token}`},signal:AbortSignal.timeout(30000)});
const body=await response.json();
if(!response.ok)throw new Error(JSON.stringify(body.errors?.map(e=>({status:e.status,title:e.title,detail:e.detail}))));
const result=(body.data??[]).map(build=>({id:build.id,build:build.attributes.version,processingState:build.attributes.processingState,uploadedDate:build.attributes.uploadedDate,version:body.included?.find(item=>item.id===build.relationships.preReleaseVersion?.data?.id)?.attributes?.version}));
const outputDirectory=`output/salonfe-release-${build}`;
fs.mkdirSync(outputDirectory,{recursive:true});
fs.writeFileSync(`${outputDirectory}/apple-build-status.json`,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
